window.JD = window.JD || {};

((JD) => {
	/**
	 * Graph — a per-repo knowledge-graph viewer. The whole page IS the framed viz
	 * (`/graph-viewer?kb=…&theme=…`), which reuses the exact same self-contained
	 * graph the CLI's `jolli graph --export` and the VS Code webview render (that
	 * repo's `graph.json` inlined). The iframe is `sandbox="allow-scripts"` WITHOUT
	 * `allow-same-origin`, isolating it from this page's mutation token.
	 *
	 * The repo switcher and the light/dark palette both live INSIDE the framed
	 * document (see `GraphViewerDocument`): switching repos self-navigates the
	 * iframe, so there is no dashboard chrome here beyond the iframe itself. This
	 * page only picks the initial repo (URL `?kb=`, else the first available) and
	 * the initial theme, then hands off to the frame. `kb` is the Memory Bank
	 * folder directory name, resolved to a path server-side (never a `repoIdentity`).
	 */

	function availableRepos(model) {
		return ((model.graph && model.graph.repos) || []).filter((r) => r.graphAvailable);
	}

	function initialKb(available) {
		var want = new URLSearchParams(window.location.search).get("kb");
		if (want && available.some((r) => r.kb === want)) return want;
		return available[0].kb;
	}

	function currentTheme() {
		var dt = document.documentElement.getAttribute("data-theme");
		if (dt === "light" || dt === "dark") return dt;
		return window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
	}

	function render(model) {
		var available = availableRepos(model);
		if (!available.length) {
			document.getElementById("app").innerHTML =
				'<section class="graph-page"><div class="empty"><div class="inner"><div class="chip">◆</div>' +
				"<h2>No graphs yet</h2><p>A knowledge graph is generated by <code>jolli compile</code>. " +
				"Once a repository has one, pick it here to explore it.</p></div></div></section>";
			return;
		}
		var kb = initialKb(available);
		var src = "/graph-viewer?kb=" + encodeURIComponent(kb) + "&theme=" + currentTheme();
		document.getElementById("app").innerHTML =
			'<section class="graph-page"><iframe class="graph-frame" sandbox="allow-scripts" ' +
			'title="Knowledge graph" src="' +
			src +
			'"></iframe></section>';
	}

	JD.renderGraph = (model) => render(model);
})(window.JD);
